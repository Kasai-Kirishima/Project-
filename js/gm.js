/* Локальный мастер текстового RP. Сцены собираются из факторов персонажа и состояния мира. */
(function(){
  const text=(v)=>String(v??'').trim();
  const dateLabel=(c)=>`${String(c?.date||1).padStart(2,'0')}.${String(c?.month||9).padStart(2,'0')}.${c?.year||2023}`;
  const periodOf=(hour)=>hour<6?'глубокой ночью':hour<11?'утром':hour<17?'днём':hour<22?'вечером':'поздним вечером';
  const weatherOf=(s)=>{
    const month=s.calendar?.month||9;
    const options=month<=2?['морозный воздух и серое небо','мелкий снег и сырой ветер','холодный туман']:
      month<=5?['прохладный ветер и влажный асфальт','переменная облачность','слабый весенний дождь']:
      month<=8?['тёплый воздух и ясное небо','тяжёлые летние облака','короткий тёплый дождь']:
      month<=10?['прохладный воздух и жёлтые листья','низкие облака и моросящий дождь','сырой осенний ветер']:
      ['холодный ветер','мокрый снег','ранние зимние сумерки'];
    return options[(Math.max(1,s.calendar?.date||1)+s.day)%options.length];
  };
  function opening(){
    const s=OD_STATE.get(),p=s.player||{},place=OD_WORLD.getPlace(s.location),team=[...OD_DATA.humanTeams,...OD_DATA.mixedTeams,...OD_DATA.possessedTeams].find(t=>t.id===s.teamId);
    const date=dateLabel(s.calendar),period=periodOf(s.hour),weather=weatherOf(s);
    const specialization=text(p.specialization)||'Универсал';
    const nature=text(p.nature),bio=text(p.bio);
    const natureLower=nature.toLowerCase();
    const personality=natureLower.match(/спокой|сдерж|тих|замкнут|молчалив/)?'Вы невольно отмечаете детали и стараетесь не привлекать лишнего внимания.':
      natureLower.match(/агресс|вспыль|резк|импульсив|дерз/)?'Вам трудно оставаться в стороне, когда ситуация начинает накаляться.':
      natureLower.match(/добр|мягк|отзыв|забот|дружелюб/)?'Вы прежде всего замечаете людей вокруг и то, кому может понадобиться помощь.':
      natureLower.match(/подозр|осторож|недовер/)?'Вы не спешите доверять окружающим и сначала оцениваете обстановку.':
      'Первые минуты проходят спокойно: вы осматриваетесь и привыкаете к обстановке.';
    const background=bio?` Из биографии особенно выделяется следующее: ${bio.slice(0,260)}${bio.length>260?'…':''}`:'';
    const trait=`Ваша специализация — «${specialization.toLowerCase()}». ${personality}`;
    const locationText=place?.name||'Берлин';
    const atmosphere=`На улице ${weather}; сейчас ${period}. Берлин, 2023 год, ${date}.`;
    let scene='';

    if(p.faction==='БПСД'&&s.startMode==='early'){
      scene=`Допрос закончен. В личном деле появилась отметка о распределении в отряд «${team?.name||'БПСД'}». Служебная машина привозит вас к месту размещения команды — ${locationText}. За дверью слышны голоса: кто-то спорит по поводу рапорта, кто-то ищет ключи от машины. На столе лежит папка с новым делом. Никто не торопится встречать новичка официальной речью.`;
      scene+=p.type==='Одержимый'?` В коридоре на секунду задерживается взгляд дежурного на вашей метке. Для одержимых здесь предусмотрены отдельные медицинские проверки и запас минерального питания.`:` Ваша команда состоит из людей. Здесь ценят дисциплину, подготовку и умение работать рядом с теми, кто сталкивается с одержимыми лицом к лицу.`;
    } else if(p.faction==='БПСД'){
      scene=`Вы просыпаетесь в расположении отряда «${team?.name||'БПСД'}» по адресу: ${locationText}. Смена уже началась. Из кухни доносится разговор о ночном вызове, в общей комнате кто-то оставил включённым телевизор, а возле входа стоит сумка с экипировкой. Вам не нужно заново знакомиться с командой — вы давно часть этой группы, хотя сегодняшнее дело ещё не раскрыто.`;
      scene+=p.type==='Одержимый'?` На полке отмечен ваш запас минеральной смеси: без него регенерация и использование Дара быстро станут проблемой.`:` На стене висит расписание патрулей. Для человека служба опасна: против одержимого нельзя полагаться только на обычную физическую силу.`;
    } else if(p.faction==='Орден'){
      scene=`Вы находитесь в тайном логове Ордена — подземном комплексе, скрытом от обычных жителей. В коридорах слышны голоса и тяжёлые шаги. Последователи Вара готовятся к очередному собранию: на стене висит карта Берлина с отмеченными точками наблюдения. Сам Вар, одержимый духом Войны, пока занят разговором со старшими участниками. Здесь каждый должен доказать пользу для общего дела.`;
      scene+=p.spirit?` Ваш дух — ${text(p.spirit)}, а Дар — «${text(p.gift)||'не указан'}». Несколько участников уже знают о вашей особенности.`:'';
    } else {
      scene=`Вы начинаете день в районе «${locationText}». ${p.home?`Ваше жильё — ${OD_WORLD.getPlace(p.home)?.name||'съёмное жильё'}.`:'Собственного жилья у вас пока нет.'} На первый взгляд город живёт привычно: люди спешат на работу, транспорт идёт по расписанию, магазины открываются.`;
      scene+=' Но в местных новостях всё чаще появляются сообщения о перекрытых улицах, пропавших животных и странных происшествиях, о которых власти говорят неохотно.';
    }

    let natureDetail=p.type==='Одержимый'
      ?` Вы — одержимый. После физиологической смерти ваше тело занял дух «${text(p.spirit)||'неизвестный дух'}». Дар: «${text(p.gift)||'не указан'}». Метка: ${text(p.mark)||'не описана'}. Для поддержания регенерации организму необходимы минералы.`
      :' Вы — человек. Вы стареете, устаёте и получаете обычные травмы; сверхъестественной защиты у вас нет.';
    if(Number(s.stats?.perception)>18) natureDetail+=' Благодаря развитому восприятию вы быстро замечаете мелкие детали обстановки.';
    if(Number(s.stats?.charisma)>18) natureDetail+=' В общении вы производите уверенное первое впечатление.';
    if(Number(s.stats?.stealth)>18) natureDetail+=' Вы привыкли двигаться осторожно и сначала оценивать возможные укрытия.';
    if(p.car) natureDetail+=` В вашем распоряжении транспорт: ${text(p.car)}.`;

    const intro=`${atmosphere}\n\n${scene}\n\n${p.name||'Вы'}, ${p.age||'неизвестного возраста'} лет. ${natureDetail} ${trait}${background}\n\nЭто ролевая игра: вы описываете только действия и слова своего персонажа. Мастер отыгрывает NPC, окружение, время и последствия. Необъявленные действия не считаются автоматически успешными; бой не начинается без явного враждебного поступка.`;
    push('',intro,'intro');
    return intro;
  }

  function push(action,reply,kind='turn'){
    OD_STATE.update(st=>{
      st.rpTurns=st.rpTurns||[];
      st.rpTurns.push({action:String(action||''),reply:String(reply||''),kind,day:st.day,time:`${String(st.hour).padStart(2,'0')}:${String(st.minute).padStart(2,'0')}`});
      st.rpTurns=st.rpTurns.slice(-40);
    });
  }

  function narrate(action,result,beforePlace){
    const state=OD_STATE.get(),p=state.player||{},afterPlace=OD_WORLD.getPlace(state.location);
    const raw=text(result),a=String(action||'').toLowerCase();
    let answer=raw;
    const moved=beforePlace&&afterPlace&&beforePlace.id!==afterPlace.id;

    if(moved){
      answer=`Вы покидаете локацию «${beforePlace.name}». ${raw} ${afterPlace.description||''} Теперь сцена продолжается здесь.`;
    } else if(state.combat&&/(напада|атак|удар|стреля|драться|сразиться)/i.test(a)){
      answer=`Вы делаете первый враждебный шаг. ${raw} Противник реагирует на нападение — теперь каждое ваше решение может повлиять на исход схватки.`;
    } else if(state.encounter&&/(провоцир|угрожа|оскорб|толка|цепляюсь)/i.test(a)){
      answer=`Обстановка становится напряжённой. ${raw} Пока никто не перешёл к драке; вы ещё можете отступить или попытаться решить конфликт словами.`;
    } else if(/(холодильник|кухн|еда|сэндвич|выпить|вода)/i.test(a)){
      answer=`Мастер учитывает бытовую обстановку в «${afterPlace?.name||'текущей локации'}». ${raw}`;
    } else if(/(поговор|спрос|привет|обращаюсь|говорю)/i.test(a)){
      answer=`${raw}`;
    } else if(/(тренир|спорт|бег|отжим|подтяг|штанг|бокс)/i.test(a)){
      answer=`Вы уделяете время физической подготовке. ${raw}`;
    } else if(/(жду|подожду|сижу|наблюдаю|слежу)/i.test(a)){
      answer=`Пока вы ждёте, город не замирает: люди проходят мимо, транспорт продолжает движение, а время идёт. ${raw}`;
    } else if(/(холодильник|мопед|душ|кроват|ноутбук|компьютер)/i.test(a)){
      answer=`Действие проверено с учётом текущей локации. ${raw}`;
    } else if(!raw){
      answer=`${p.name||'Вы'} предпринимаете действие в локации «${afterPlace?.name||'неизвестно'}». Опишите подробнее, что именно хотите сделать.`;
    }

    push(action,answer,'turn');
    OD_STATE.addLog(`Вы: ${action} · ${answer}`);
    return answer;
  }

  function wrap(){
    const original=OD_INTERPRETER.handle;
    OD_INTERPRETER.handle=function(action){
      const before=OD_WORLD.getPlace(OD_STATE.get().location);
      const result=original(action);
      return narrate(String(action||''),result,before);
    };
  }
  window.OD_GM={opening,push,narrate,wrap};
  wrap();
})();
